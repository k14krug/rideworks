/* Run against preview_race_results.py --full-case; entirely synthetic. */
async page => {
  const base = new URL(page.url()).origin;
  let checks = 0;
  const check = (condition, message) => { checks++; if (!condition) throw Error(message); };
  await page.setViewportSize({width: 1440, height: 1000});
  await page.goto(base + '/race-results/import');
  check(await page.locator('select[name=mode]').inputValue() === 'full', 'full image is selected by default');
  check((await page.locator('select[name=mode]').innerText()).includes('fallback'), 'sectioning is optional');
  await page.evaluate(async () => {
    const canvas = document.createElement('canvas');
    canvas.width = 1525; canvas.height = 1864;
    const ctx = canvas.getContext('2d');
    ctx.fillStyle = 'white'; ctx.fillRect(0, 0, canvas.width, canvas.height);
    ctx.fillStyle = 'black'; ctx.font = '24px sans-serif';
    for (let i = 0; i < 17; i++) ctx.fillText(`Synthetic race ${i + 1}`, 20, 80 + i * 100);
    const blob = await new Promise(resolve => canvas.toBlob(resolve, 'image/png'));
    const files = new DataTransfer();
    files.items.add(new File([blob], 'synthetic-full.png', {type: 'image/png'}));
    document.querySelector('input[name=image]').files = files.files;
  });
  await page.locator('input[name=timezone]').fill('UTC');
  await page.getByRole('button', {name: 'Extract screenshot'}).click();
  const rows = page.locator('.race-candidate-row');
  check(await rows.count() === 17, '17 race rows');
  check(await page.locator('.race-overlap').count() === 0, 'zero overlap questions');
  check((await page.locator('.race-review-summary').innerText()).includes('17 automatically matched'), '17 automatic matches');
  check((await page.locator('.race-review-summary').innerText()).includes('0 matching errors'), 'zero matching errors');
  check((await page.locator('.race-review-actions').innerText()).includes('11 restorations to approve'), '11 restorations distinguished');
  check(!(await page.locator('main').innerText()).includes('need attention'), 'no generic attention count');
  check(await page.locator('input[name=restore_displayed]').count() === 1, 'one explicit restoration consent');
  check(await page.locator('input[name$=".replace"]').count() === 0, 'no per-row restoration forms');
  check(!(await page.getByText('Technical details', {exact: true}).evaluate(el => el.parentElement.open)), 'technical details collapsed');
  check(await page.locator('.race-fields:visible').count() === 0, 'ordinary rows stay compact');
  await page.screenshot({path: 'output/playwright/race02-full-desktop.png'});
  await page.locator('input[name=list_acknowledged]').check();
  check(await page.locator('button[value=confirm]').isDisabled(), 'list acknowledgment alone does not approve restoration');
  await page.locator('input[name=restore_displayed]').check();
  check(await page.locator('button[value=confirm]').isEnabled(), 'specific bulk consent permits the matched batch');
  await rows.first().getByText('Edit', {exact: true}).click();
  await page.locator('input[name="0.avg_watts"]').fill('161');
  check(!(await page.locator('input[name=restore_displayed]').isChecked()), 'editing clears restoration consent');
  check(await page.locator('button[value=confirm]').isDisabled(), 'edited batch requires review');
  await page.getByRole('button', {name: 'Review changes'}).click();
  await rows.last().getByText('Edit', {exact: true}).click();
  await page.locator('input[name="16.date"]').fill('2024-06-20');
  await page.getByRole('button', {name: 'Review changes'}).click();
  check((await rows.last().innerText()).includes('Activity match unavailable'), 'missing activity is distinct from OCR errors');
  check((await rows.last().innerText()).includes('sync coverage'), 'useful missing-activity explanation');
  await page.locator('input[name=restore_displayed]').check();
  await page.locator('input[name=list_acknowledged]').check();
  check(await page.locator('button[value=confirm]').isDisabled(), 'one missing activity blocks all writes');
  await rows.last().getByText('Edit', {exact: true}).click();
  await page.locator('input[name="16.date"]').fill('2024-03-17');
  await page.getByRole('button', {name: 'Review changes'}).click();
  await page.setViewportSize({width: 390, height: 900});
  check(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), 'mobile page has no overflow');
  check(await rows.count() === 17, 'mobile retains all 17 rows');
  check(await page.locator('.race-fields:visible').count() === 0, 'mobile edits remain collapsed');
  check(await page.locator('input[name=restore_displayed]').isVisible(), 'mobile exposes one clear restoration consent');
  await page.screenshot({path: 'output/playwright/race02-full-mobile.png'});
  await page.locator('input[name=restore_displayed]').check();
  await page.locator('input[name=list_acknowledged]').check();
  await page.getByRole('button', {name: 'Import all 17 races', exact: true}).click();
  check((await page.locator('main').innerText()).includes('Added 17'), 'atomic 17-race import');
  await page.goto(base + '/race-results');
  check(await page.getByRole('link', {name: 'Remove race result'}).count() === 17, 'all restored/new results available');
  return `${checks} synthetic full-image browser checks passed; no paid API request.`;
}
