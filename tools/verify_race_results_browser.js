/* Playwright check against preview_race_results.py's mock-only server. */
async page => {
  const base = new URL(page.url()).origin;
  let checks = 0;
  const check = (condition, message) => { checks++; if (!condition) throw Error(message); };
  await page.setViewportSize({width: 1440, height: 900});
  await page.goto(base + '/race-results/import');
  check((await page.locator('main').innerText()).includes('sends the screenshot to OpenAI'), 'API disclosure');
  await page.evaluate(async () => {
    const canvas = document.createElement('canvas');
    canvas.width = 768; canvas.height = 939;
    const context = canvas.getContext('2d');
    context.fillStyle = 'white'; context.fillRect(0, 0, canvas.width, canvas.height);
    context.fillStyle = 'black'; context.font = '20px sans-serif';
    for (let i = 0; i < 17; i++) context.fillText(`Synthetic row ${i + 1}`, 10, 30 + i * 50);
    const blob = await new Promise(resolve => canvas.toBlob(resolve, 'image/png'));
    const files = new DataTransfer();
    files.items.add(new File([blob], 'synthetic.png', {type: 'image/png'}));
    document.querySelector('input[name=image]').files = files.files;
  });
  await page.locator('input[name=timezone]').fill('UTC');
  await page.getByRole('button', {name: 'Extract screenshot'}).click();
  check(await page.locator('.race-candidate-row').count() === 3, 'all three observations retained');
  check(await page.locator('button[value=confirm]').isDisabled(), 'unreviewed batch blocked');
  check((await page.locator('main').innerText()).includes('Estimated API cost:'), 'estimate disclosed');
  await page.locator('input[name="overlap.1.2"][value=same]').check();
  await page.getByText('Compare screenshot crops').click();
  check(await page.locator('.race-crop-comparison img').count() >= 2, 'both crop contexts available');
  await page.getByRole('button', {name: 'Review changes'}).click();
  check((await page.locator('main').innerText()).includes('2 automatically matched'), 'automatic matching shown');
  check((await page.locator('.race-conflict').innerText()).includes('Race avg W: 175 / 180'), 'both conflicting watts shown');
  check((await page.locator('main').innerText()).includes('1 need attention'), 'conflict appears in status summary');
  await page.locator('input[name=list_acknowledged]').check();
  check(await page.locator('button[value=confirm]').isDisabled(), 'general acknowledgment does not verify conflicting values');
  await page.locator('input[name="verify.1.2"]').check();
  check(await page.locator('button[value=confirm]').isEnabled(), 'pair verification permits matched batch');
  await page.locator('.race-candidate-row').nth(1).getByText('Edit', {exact: true}).click();
  await page.locator('input[name="1.avg_watts"]').fill('176');
  check(!(await page.locator('input[name="verify.1.2"]').isChecked()), 'editing invalidates pair verification');
  check(await page.locator('button[value=confirm]').isDisabled(), 'edited batch requires another review');
  await page.locator('input[name="1.avg_watts"]').fill('175');
  await page.getByRole('button', {name: 'Review changes'}).click();
  check(await page.locator('button[value=confirm]').isDisabled(), 'list acknowledgment required');
  check(!(await page.locator('input[name="verify.1.2"]').isChecked()), 'reviewed edits require renewed pair verification');
  await page.locator('input[name="verify.1.2"]').check();
  await page.locator('input[name=list_acknowledged]').check();
  check(await page.locator('button[value=confirm]').isEnabled(), 'acknowledged list can be confirmed');
  await page.setViewportSize({width: 390, height: 900});
  check(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), 'no mobile overflow');
  await page.locator('button[value=confirm]').click();
  check((await page.locator('main').innerText()).includes('Added 2'), 'whole reconciled batch saved');
  await page.setViewportSize({width: 1440, height: 900});
  await page.goto(base + '/activities');
  const activities = await page.locator('main').innerText();
  check(activities.includes('Racing Score') && activities.includes('Race avg W'), 'race columns displayed');
  check(activities.includes('233 W') && activities.includes('161 W') && activities.includes('175 W'), 'activity and race watts remain distinct');
  await page.goto(base + '/race-results');
  check((await page.locator('main').innerText()).includes('175 W'), 'reviewed race watts displayed');
  await page.getByRole('link', {name: 'Remove race result'}).first().click();
  check((await page.locator('main').innerText()).includes('The activity, FIT data, source screenshot and result history will be retained'), 'removal confirmation');
  return `${checks} synthetic browser checks passed; no OpenAI request was made.`;
}
